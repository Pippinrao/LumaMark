describe('i18n resources', () => {
  it('provides English and Simplified Chinese values for every core UI key', async () => {
    for (const language of ['en', 'zh-CN'] as const) {
      const translation = resources[language].translation;

      for (const key of requiredCoreKeys) {
        expect(translation[key], `${language} is missing ${key}`).toEqual(
          expect.any(String),
        );
        expect(translation[key].trim(), `${language} has an empty ${key}`).not
          .toBe('');
      }
    }
  });

  it('defaults to Simplified Chinese when no persisted language is configured', async () => {
    expect(defaultLanguage).toBe('zh-CN');
    expect(i18n.options.fallbackLng).toContain('zh-CN');
    expect(i18n.exists('app.name')).toBe(true);
    expect(i18n.t('status.ready')).toBe('就绪');
    expect(i18n.t('status.ready', { lng: 'zh-CN' })).toBe('就绪');
  });

  it.each([
    ['en', 'A modern, high-performance Markdown editor'],
    ['zh-CN', '现代、高性能的 Markdown 编辑器'],
  ] as const)('uses neutral product copy in the About dialog for %s', (language, expected) => {
    const description = resources[language].translation['about.description'];

    expect(description).toBe(expected);
    expect(description).not.toMatch(/typora/i);
  });

  it.each([
    ['en', 'Your current document was not changed.'],
    ['zh-CN', '当前文档内容未被更改。'],
  ] as const)(
    'keeps file-operation safety copy in %s',
    (language, expected) => {
      expect(
        resources[language].translation['fileError.documentSafe'],
      ).toBe(expected);
    },
  );

  it.each([
    ['en', 'Check the current document state before continuing.'],
    ['zh-CN', '继续前请确认当前文档状态。'],
  ] as const)(
    'uses neutral document-state guidance for desktop errors in %s',
    (language, expected) => {
      expect(
        resources[language].translation['fileError.documentStatus'],
      ).toBe(expected);
    },
  );
});
